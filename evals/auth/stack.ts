/**
 * stack.ts — the POC's secrets, certificate and compose project (SMD-2285).
 *
 * One compose project per candidate, `ob1-auth-<candidate>`: compose.yaml plus
 * compose.<candidate>.yaml, so `--down` removes its containers, networks and
 * image and nothing else. compose runs with the orchestration kit's
 * allowlisted environment (evals/orchestration/stack.ts `run`), so a dogfood
 * deploy/.env on the search path reaches nothing here.
 *
 * evals/auth/.env (gitignored, `.env` at any depth) is written once and reused:
 * the origin and its port, the signing key (one P-256 JWK), the cookie keys,
 * each static client's secret, and the operator's password beside its argon2id
 * hash. The verifier reads the password; the server sees only the hash. JSON
 * and hash values are single-quoted, so compose does not read their `$`s as
 * variables. The certificate cimd.test serves is written to evals/auth/.poc/
 * (gitignored) and trusted by the server alone.
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseEnv } from "../../db/env.ts";
import { run, type Run } from "../orchestration/stack.ts";
import { layout } from "./policy.ts";

export const HERE = dirname(fileURLToPath(import.meta.url));
export const ENV_FILE = join(HERE, ".env");
const POC_DIR = join(HERE, ".poc");
export const CANDIDATES = ["oidc-provider", "better-auth"] as const;
export type Candidate = (typeof CANDIDATES)[number];

const DEFAULT_PORT = "8020";

export async function ensureEnv(): Promise<Record<string, string>> {
  const hex = (n: number) => randomBytes(n).toString("hex");
  if (existsSync(ENV_FILE)) {
    // A client added to policy.ts since the file was written gets its secret appended; nothing else is rewritten.
    const env = parseEnv(readFileSync(ENV_FILE, "utf8"));
    const missing = Object.keys(layout(env.OB1_PUBLIC_ORIGIN ?? `http://localhost:${DEFAULT_PORT}`).clients)
      .map((id) => `OB1_AUTH_SECRET_${id.toUpperCase().replace(/-/g, "_")}`)
      .filter((k) => !env[k]);
    if (missing.length) writeFileSync(ENV_FILE, readFileSync(ENV_FILE, "utf8") + missing.map((k) => `${k}=${hex(24)}\n`).join(""), { mode: 0o600 });
    return parseEnv(readFileSync(ENV_FILE, "utf8"));
  }
  const { privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = { ...privateKey.export({ format: "jwk" }), kid: `poc-${hex(4)}`, alg: "ES256", use: "sig" };
  const password = `Poc-${hex(12)}`;
  const L = layout(`http://localhost:${DEFAULT_PORT}`);
  const secrets = Object.keys(L.clients).map((id) => `OB1_AUTH_SECRET_${id.toUpperCase().replace(/-/g, "_")}=${hex(24)}`);
  const lines = [
    "# SMD-2285 authorization-server POC. Generated by eval-auth.ts --up; gitignored.",
    `AUTH_POC_PORT=${DEFAULT_PORT}`,
    `OB1_PUBLIC_ORIGIN=${L.origin}`,
    `OB1_AUTH_JWKS='${JSON.stringify({ keys: [jwk] })}'`,
    `OB1_AUTH_COOKIE_KEYS=${hex(32)},${hex(32)}`,
    `OB1_AUTH_OPERATOR_PASSWORD=${password}`,
    `OB1_AUTH_OPERATOR_PASSWORD_HASH='${await Bun.password.hash(password, { algorithm: "argon2id" })}'`,
    ...secrets,
    "",
  ];
  writeFileSync(ENV_FILE, lines.join("\n"), { mode: 0o600 });
  return parseEnv(readFileSync(ENV_FILE, "utf8"));
}

/** cimd.test's self-signed certificate and key, made once with the host's openssl. */
export function ensureCert(): string[] {
  const cert = join(POC_DIR, "cimd.pem");
  if (existsSync(cert)) return [];
  mkdirSync(POC_DIR, { recursive: true });
  const r = run([
    "openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes",
    "-keyout", join(POC_DIR, "cimd.key"), "-out", cert, "-days", "30",
    "-subj", "/CN=cimd.test", "-addext", "subjectAltName=DNS:cimd.test",
  ]);
  if (r.code !== 0) throw new Error(`openssl failed: ${r.err.trim()}`);
  // The containers run as `bun`, not the host user: the throwaway key must be readable to them.
  run(["chmod", "644", join(POC_DIR, "cimd.key")]);
  return ["wrote a self-signed certificate for cimd.test to evals/auth/.poc/"];
}

export function compose(candidate: Candidate, args: string[]): Run {
  return run(["docker", "compose", "-p", `ob1-auth-${candidate}`, "--env-file", ENV_FILE, "-f", join(HERE, "compose.yaml"), "-f", join(HERE, `compose.${candidate}.yaml`), ...args]);
}

/** A service's log since the project started, without prefixes. A failed read throws: an empty log would pass for silence. */
export function logsOf(candidate: Candidate, service: string): string {
  const r = compose(candidate, ["logs", "--no-color", "--no-log-prefix", service]);
  if (r.code !== 0) throw new Error(`could not read ${service}'s log: ${r.err.trim()}`);
  return r.out;
}

export function docker(args: string[]): Run {
  return run(["docker", ...args]);
}

/**
 * A reader of the lines each service logs from now on. A second verify on one
 * stack must find its own evidence, not the first run's, so the verifier
 * counts each log's lines at its start and reads only what follows.
 */
export function logsFromNow(candidate: Candidate, services: string[]): (service: string) => string {
  const lines = (s: string) => logsOf(candidate, s).split("\n").filter(Boolean);
  const marks = Object.fromEntries(services.map((s) => [s, lines(s).length]));
  return (service) => lines(service).slice(marks[service] ?? 0).join("\n");
}
